package core.operations;

public class UnaryTask {

	public static void main(String[] args) {
		int a = 12;
		System.out.println(a);
		System.out.println(a++);
		System.out.println(++a);
		System.out.println(--a);
		System.out.println(a);
		System.out.println(a--);
		System.out.println(a++);
		System.out.println(a);
	}

}
