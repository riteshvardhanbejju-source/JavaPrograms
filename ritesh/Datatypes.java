package ritesh;

public class Datatypes {
	byte b;
	int a;
	boolean result;
	char ch;
	float sal;
	String name;
	
	public static void main(String[] args) {
		//instantiation- creating object
		Datatypes dt= new Datatypes();
		
		System.out.println("byte default value = "+dt.b);
		System.out.println("int default value = "+dt.a);
		System.out.println("boolean default value = "+dt.result);
		System.out.println("char default value = "+dt.ch);
		System.out.println("float default value = "+dt.sal);
		System.out.println("string default value = "+dt.name);
	}

}
